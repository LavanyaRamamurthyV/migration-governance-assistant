import config
from pipeline.spec import FEEDS, LAYOUT_V2_EFFECTIVE, TABLE_BY_HUB, TABLES

HEADER_NOTE = (
    "Data: Olist Brazilian E-Commerce Public Dataset (Kaggle, CC BY-NC-SA 4.0). "
    "Source system label: Teradata (stand-in: Olist CSV extract). Target: Data Hub (SQLite stand-in)."
)


def _scalar(con, sql):
    row = con.execute(sql).fetchone()
    return row[0] if row and row[0] is not None else 0


def _source_stats(leg, table, column):
    n, nulls, maxlen = leg.execute(
        f"SELECT COUNT(*), SUM({column} IS NULL), MAX(LENGTH({column})) FROM {table}").fetchone()
    sample = leg.execute(f"SELECT {column} FROM {table} WHERE {column} IS NOT NULL LIMIT 1").fetchone()
    return dict(rows=n, null_pct=(nulls or 0) / max(n, 1) * 100, maxlen=maxlen or 0, sample=sample[0] if sample else None)


def _source_type(kind, maxlen):
    return {"int": "INTEGER stored as text", "dec2": "DECIMAL stored as text",
            "float": "DOUBLE stored as text", "ts": "TIMESTAMP stored as text"}.get(kind, f"VARCHAR({maxlen})")


# ------------------------------------------------------------------ mapping
def mapping_doc(ctx, leg):
    recon = {t["table"]: t for t in ctx["recon"]["tables"]}
    total = sum(len(t["columns"]) for t in TABLES)
    out = [
        "# Source-to-target mapping: legacy (Teradata stand-in) to Data Hub", "",
        HEADER_NOTE, "",
        f"This mapping covers {len(TABLES)} hub tables and {total} mapped fields. Every rule, type, null rate and status "
        "below was generated by the migration pipeline from the real files.", "",
    ]
    n = 0
    for t in TABLES:
        r = recon[t["hub_table"]]
        out += [f"## {t['hub_table']}", "",
                f"Source file: {t['source_file']}. Data owner: {t['owner']}. Consuming teams: {', '.join(t['consumers'])}. "
                f"Rows migrated: {r['hub_rows']:,}. Reconciliation status: {r['status']}.",
                f"PII fields in {t['hub_table']} (flag Y): {', '.join(c['tgt'] for c in t['columns'] if c['pii'] == 'Y') or 'none'}. "
                f"Quasi-identifier fields: {', '.join(c['tgt'] for c in t['columns'] if c['pii'] == 'Quasi') or 'none'}.", ""]
        for c in t["columns"]:
            n += 1
            if c.get("lookup"):
                stg, srccol, srcname = "stg_translation", "product_category_name_english", "product_category_name_translation"
            else:
                stg, srccol, srcname = f"stg_{t['name']}", c["src"], t["source_file"].replace(".csv", "")
            st = _source_stats(leg, stg, srccol)
            sample = "(free text, not sampled)" if c["kind"] == "text_mask" else str(st["sample"])[:40]
            status = "Validated" if r["status"] == "PASS" else "Failed validation"
            src_ref = f"{srcname}.{c['src'].split('.')[-1]}"
            out += [
                f"### MAP-{n:03d}: {c['tgt']}", "",
                f"Summary: {t['hub_table']}.{c['tgt']} is populated from {src_ref} in the legacy extract. Rule: {c['rule']}",
                f"Source column: {src_ref} ({_source_type(c['kind'], st['maxlen'])}, {st['null_pct']:.1f}% null)",
                f"Target column: {t['hub_table']}.{c['tgt']} ({c['ttype']})",
                f"Transformation rule: {c['rule']}",
                f"PII flag: {c['pii']}",
                f"Data owner: {t['owner']}",
                f"Consuming teams: {', '.join(t['consumers'])}",
                f"Status: {status}",
                f"Sample source value: {sample}", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ layout
def layout_doc(ctx, hub):
    max_status = _scalar(hub, "SELECT MAX(LENGTH(order_status)) FROM hub_order")
    out = [
        "# Record layout: v1.1 (current) and v2.0 (proposed)", "",
        HEADER_NOTE, "",
        "Layout v1.1 is the layout actually produced by this migration. Layout v2.0 is a PROPOSED DEMO CHANGE: "
        "it shows how a target record layout update is documented, approved and communicated per policy P-06.", "",
        "## Current layout v1.1", ""]
    for t in TABLES:
        out += [f"### {t['hub_table']} layout v1.1", "",
                f"Consuming teams: {', '.join(t['consumers'])}. Fields in record order (position, name, type):"]
        for i, c in enumerate(t["columns"], 1):
            out.append(f"{i}. {c['tgt']} {c['ttype']}")
        out.append("")

    changes = [
        ("CHG-001", "hub_customer.consent_flag", "New field", "not present",
         "consent_flag CHAR(1), default 'U' (U = unknown, Y = consented, N = declined)",
         ["Marketing", "Customer Experience"], "Marketing needs the consent state before any campaign use."),
        ("CHG-002", "hub_customer.customer_region_cd", "New field", "not present",
         "customer_region_cd CHAR(2), derived from customer_state (N, NE, CO, SE, S)",
         ["Marketing", "Logistics"], "Regional reporting without joining a state lookup in every feed."),
        ("CHG-003", "hub_order.order_status", "Modified field",
         f"VARCHAR(12), longest observed value is {max_status} characters",
         "VARCHAR(20)", ["Logistics", "Finance", "Marketing"],
         "Headroom for new order statuses without another layout change."),
        ("CHG-004", "hub_payment.payment_value_brl", "Modified field", "DECIMAL(18,2)", "DECIMAL(18,4)",
         ["Finance"], "Finance wants extra precision for installment and currency calculations."),
        ("CHG-005", "hub_review.pii_masked_flag", "New field", "not present",
         "pii_masked_flag CHAR(1), 'Y' when masking changed the comment text",
         ["Customer Experience"], "Makes the PII control visible to downstream users."),
        ("CHG-006", "hub_order_item.currency_cd", "New field", "not present",
         "currency_cd CHAR(3), default 'BRL'", ["Finance"], "Prices are implicitly BRL today; make it explicit."),
    ]
    out += ["## Proposed changes in layout v2.0 (demo change)", "",
            f"Effective date for all changes below: {LAYOUT_V2_EFFECTIVE} (demo value). "
            "Policy P-06 requires an impact analysis, 10 business days notice, and sign-off from every consuming team.", ""]
    for cid, field, ctype, v1, v2, teams, why in changes:
        out += [f"### {cid}: {field} ({ctype})", "",
                f"Field: {field}", f"Change type: {ctype}", f"v1 value: {v1}", f"v2 value: {v2}",
                f"Effective date: {LAYOUT_V2_EFFECTIVE} (demo)", f"Impacted teams: {', '.join(teams)}",
                f"Reason: {why}", "Sign-off status: Pending", ""]
    out += ["## Version history", "",
            "### Version v1.0", "Date: 2026-11-02 (demo). Change: initial hub layout created from the legacy extract. Approver role: Data Governance Lead. Status: Superseded.", "",
            "### Version v1.1", "Date: 2026-11-06 (demo). Change: fixed the legacy typo 'lenght' to 'length' in two hub_product fields. Approver role: Data Architecture Lead. Status: Current.", "",
            "### Version v2.0", f"Effective date: {LAYOUT_V2_EFFECTIVE} (demo). Change: CHG-001 to CHG-006 above. Approver roles: one per consuming team (Marketing, Finance, Logistics, Customer Experience, Seller Ops). Status: Proposed, sign-offs pending.", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ sunset plan
def sunset_doc(ctx):
    findings = ctx["recon"]["findings"]
    out = [
        "# Legacy G sunset plan (demo)", "",
        "Legacy G is this demo's name for the legacy platform being retired, a stand-in for a Genesis-style sunset. "
        "Phase dates and owner roles are DEMO VALUES. The blockers and warnings are NOT invented: they come from the real "
        "reconciliation findings in reconciliation_report.md.", "",
        "## Phases", "",
        "### Phase 1: Inventory", "Dates: 2026-11-16 to 2026-12-04 (demo). List every feed that reads from Legacy G, its owner, and its hub tables.", "",
        "### Phase 2: Parallel run", "Dates: 2026-12-07 to 2027-03-07 (demo). Run Legacy G and the Data Hub side by side for 90 days, as required by policy P-07, and compare outputs.", "",
        "### Phase 3: Cutover", "Dates: 2027-03-08 to 2027-03-12 (demo). Move each feed to the hub on its own cutover date after the consuming team signs off.", "",
        "### Phase 4: Decommission", "Dates: 2027-03-15 to 2027-03-26 (demo). Archive, then switch off Legacy G once there are zero active consumers and governance has signed off (policy P-07).", "",
        "## Consumer inventory", ""]
    for f in FEEDS:
        blockers, warnings = [], []
        for fd in findings:
            if f["team"] in fd["teams"]:
                (blockers if fd["blocking"] else warnings).append(f"{fd['id']} {fd['title']} ({fd['count']:,})")
        if f["extra_blocker"]:
            blockers.append(f["extra_blocker"])
        status = "Blocked" if blockers else ("Ready with warnings" if warnings else "Ready for parallel run")
        out += [f"### Feed {f['feed']} ({f['team']})", "",
                f"Team: {f['team']}", f"Owner role: {f['owner_role']}", f"Feed name: {f['feed']}",
                f"Legacy G dependency: {f['legacy_dependency']}",
                f"Hub tables: {', '.join(f['tables'])}",
                f"Cutover date (demo): {f['cutover']}",
                f"Migration status: {status}",
                f"Blockers: {'; '.join(blockers) if blockers else 'none'}",
                f"Warnings: {'; '.join(warnings) if warnings else 'none'}", ""]
    out += ["## Risks", "",
            "### Risk R-01: late sign-offs", "Layout v2.0 needs sign-off from five consuming teams. A single late sign-off moves that team's cutover date.", "",
            "### Risk R-02: join key change for Marketing", "The hub stores customer_person_token, not the raw customer_unique_id, so campaign joins must be rebuilt and re-tested.", "",
            "### Risk R-03: unresolved data-quality findings", "Open blocking findings in the reconciliation report must be resolved or formally accepted by the data owner before cutover.", "",
            "### Risk R-04: parallel-run cost", "Running two platforms for 90 days doubles storage and monitoring effort. Track it weekly.", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ reconciliation report
def recon_doc(ctx):
    r = ctx["recon"]
    now = dt.datetime.now().strftime("%Y-%m-%d")
    out = ["# Reconciliation report", "", HEADER_NOTE, "",
           f"Run date: {now}. Result: {r['tables_passed']} of {r['tables_total']} hub tables PASS. "
           f"Thresholds from policy P-05: row counts must match exactly; money totals within {config.AMOUNT_TOLERANCE_PCT}%; "
           f"null-rate drift at most {config.NULL_RATE_TOLERANCE_PP} percentage points; key uniqueness preserved.", "",
           "## Summary", "",
           "| Hub table | Source rows | Hub rows | Row match | Max null drift (pp) | Status |",
           "|---|---|---|---|---|---|"]
    for t in r["tables"]:
        out.append(f"| {t['table']} | {t['source_rows']:,} | {t['hub_rows']:,} | {'Yes' if t['row_match'] else 'NO'} | "
                   f"{t['null_check']['max_drift_pp']} | {t['status']} |")
    out += ["", "## Table results", ""]
    for t in r["tables"]:
        lines = [f"### {t['table']} reconciliation", "",
                 f"Source rows: {t['source_rows']:,}. Hub rows: {t['hub_rows']:,}. Row counts match: {'yes' if t['row_match'] else 'NO'}. Status: {t['status']}."]
        for a in t["amount_checks"]:
            lines.append(f"Amount check {a['column']}: source total {a['source_sum']:,.2f}, hub total {a['hub_sum']:,.2f}, "
                         f"difference {a['diff_pct']}% ({'pass' if a['passed'] else 'FAIL'}).")
        nc = t["null_check"]
        lines.append(f"Null-rate check: {nc['columns_checked']} columns, largest drift {nc['max_drift_pp']} pp "
                     f"(column {nc['worst_column']}), {'pass' if nc['passed'] else 'FAIL'}.")
        k = t["key_check"]
        if k:
            lines.append(f"Key check on {', '.join(k['key'])}: {k['source_distinct']:,} distinct in source, {k['hub_distinct']:,} in hub. "
                         f"Unique in source: {'yes' if k['unique_in_source'] else 'NO'}. Uniqueness preserved by migration: {'yes' if k['preserved'] else 'NO'}.")
        tk = t["token_check"]
        if tk:
            lines.append(f"Tokenization check: {tk['source_distinct_persons']:,} distinct customer_unique_id values became "
                         f"{tk['hub_distinct_tokens']:,} distinct customer_person_token values ({tk['collisions']} collisions).")
        out += lines + [""]
    out += ["## Referential integrity", "", "### Referential integrity checks"]
    out += [f"{x['check']}: {x['orphans']:,} orphan rows." for x in r["referential"]]
    out += ["", "## PII controls during migration", "",
            "### PII controls applied during migration",
            "customer_unique_id is tokenized (SHA-256 with a secret salt, first 16 hex characters). The raw value is not stored in the hub.",
            f"Free-text review fields were scanned for emails, phone numbers, national ids and long identifiers. Items masked: {ctx['migration_mask'] or 'none found'}.",
            "Zip code prefixes are kept as 5-character strings and classified as quasi-identifiers.", "",
            "## Data-quality findings", ""]
    for f in r["findings"]:
        out += [f"### {f['id']}: {f['title']}", "",
                f"Finding {f['id']}: {f['title']}. Count: {f['count']:,}.",
                f"Impacted teams: {', '.join(f['teams'])}",
                f"Blocks cutover: {'yes' if f['blocking'] else 'no (warning)'}",
                f"Recommendation: {f['recommendation']}", f"Status: {f['status']}", ""]
    return "\n".join(out)


def run(ctx):
    config.DOCS_UNMASKED.mkdir(parents=True, exist_ok=True)
    leg = sqlite3.connect(config.LEGACY_DB)
    hub = sqlite3.connect(config.HUB_DB)
    docs = {
        "mapping_teradata_to_hub.md": mapping_doc(ctx, leg),
        "record_layout_v2.md": layout_doc(ctx, hub),
        "legacy_g_sunset_plan.md": sunset_doc(ctx),
        "reconciliation_report.md": recon_doc(ctx),
    }
    leg.close()
    hub.close()
    for name, text in docs.items():
        (config.DOCS_UNMASKED / name).write_text(text, encoding="utf-8")
    return f"{len(docs)} documents generated from real schema and results"
